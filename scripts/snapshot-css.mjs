// Regenerate src/preview/site.snapshot.csstxt from a built copy of the website:
//   node scripts/snapshot-css.mjs ../arman-hosseini/dist
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const dist = process.argv[2] || '../arman-hosseini/dist';
let css = '';
for (const f of readdirSync(path.join(dist, '_astro')).filter((n) => n.endsWith('.css')).sort()) css += readFileSync(path.join(dist, '_astro', f), 'utf8') + '\n';
const html = readFileSync(path.join(dist, 'en/projects/vegord/index.html'), 'utf8');
for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) css += m[1] + '\n';
css = css.replace(/@font-face\s*\{[^}]*\}/g, '');
writeFileSync('src/preview/site.snapshot.csstxt', '/* generated by scripts/snapshot-css.mjs */\n' + css);
console.log(`snapshot: ${(css.length / 1024).toFixed(0)} KB`);
